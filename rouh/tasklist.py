"""`workspace/_tasks.md`, generated out of the database rather than written by hand.

Petar, 6 October 2026, by voice, on hearing that nothing read the task list out of
the database yet: "yes I would like that. shouldn't we do it this way?" Until then
`_tasks.md` was one hand-written paragraph per task, about 1,075 lines and 32,000
words, loaded into every conversation an agent had in the workspace. The paragraphs
had been meant to be 50 to 90 words (task 48, 48-01-05); task 30's alone was 12,000.

**What the file is now.** A view of the `task` rows: for every numbered task its
number, title, project, status and summary, the person's own live ones first, then
the live ones made for somebody else under a heading of their own, each saying who it
was for (`rouh/task_origin.py`, Petar, 15 October 2026: "I don't want those to pollute
my workspace"), and the archived ones after them, each once. Nothing in it is kept anywhere but the database:

    the number, the title     the row (`.object.json` for the title, on disk)
    the project               the `owns` links, as the projects' titles
    the status                the row's `status`
    the summary               the row's `summary`

For one day the summary and the status were written in a file in each task's folder and
taken into the row from there. Petar, the same 6 October 2026: "we want the database
to be the source. and we don't want 2 copies of the same thing." So both are the row's
alone, changed with `rouh-task status|summary` (`rouh/taskrecord.py`), every
change kept in `task_change` with who made it, and no file carries either.

**When it is made.** Whenever the rows may say something new: a status or a summary
changed (`taskrecord.change`), a reconcile that took a task in or renamed one;
anything Rouh writes into the tree (`objecttree.WRITTEN`: a task made, moved, renamed,
removed); archiving; and on the saver's own pass every few minutes, which catches a
title changed any other way. Making it again when nothing changed writes nothing.

**How it reaches git.** The server's workspace is a checkout that every deploy resets
to main, so the file Rouh writes there would last until the next deploy. The saver
(`rouh/saving.py`) puts it into main whenever it differs from main's copy, as its own
commit, through `land.sh`, so the workspace in git stays readable without Rouh
running. Nothing else commits it: a job never edits it, and an edit by hand is
replaced the next time it is made, which the file says at its top.
"""
from __future__ import annotations

import argparse
import logging
import os
import sys
from pathlib import Path

from . import fileutil

log = logging.getLogger("rouh.tasklist")

#: The file, at the workspace's root.
NAME = "_tasks.md"

#: What the file says about itself before the first task. Fixed text, with no date
#: and no count in it, so the same rows always make the same bytes and a pass with
#: nothing new has nothing to save.
HEAD = """# Tasks

<!-- Generated by Rouh from its database (rouh/tasklist.py). Do not edit this file by hand. -->

> **This file is generated. Do not edit it by hand.**
> Rouh writes it out of its database whenever a task is made, renamed, moved, changes status or gets a new summary, and saves it to main itself; anything written here by hand is replaced the next time it is made.
> A task's status and summary are kept in Rouh's database and nowhere else. Change them with `rouh-task status <number> <status>` and `rouh-task summary <number> "<50 to 90 words>"`, from the workspace.
> The title is in the task's `.object.json`, and the project is the folder it is in.

One paragraph per task: what it is, where it stands, what is open.
Everything else about a task is in its own `AGENTS.md`, in the task's folder under the project that owns it.
"""

#: What a task with nothing written yet says instead of a summary.
NO_SUMMARY = "No summary yet: give it one with `rouh-task summary`."

#: The row's five statuses, as the line says them.
STATES = {"not-started": "not started", "in-progress": "in progress",
          "waiting": "waiting on ‹owner›", "stopped": "stopped", "done": "done"}


def render(store) -> str:
    """The whole file, out of the rows. Every numbered task once; steps are not tasks here."""
    tasks = [t for t in store.list_tasks(limit=1_000_000) if t.number is not None]
    projects = {p.id: p for p in store.list_projects(limit=1_000_000)}
    owner: dict[str, tuple[str, str]] = {}
    for src_type, src_id, _dst_type, dst_id in store.owns_edges():
        owner[dst_id] = (src_type, src_id)
    titles = {t.id: t.title for t in store.list_tasks(limit=1_000_000)}

    def where(ident: str) -> str:
        """The projects a task is under, outermost first, by title."""
        names: list[str] = []
        at, seen = owner.get(ident), 0
        while at is not None and seen < 32:
            kind, oid = at
            if kind == "project" and oid in projects:
                names.append(projects[oid].title)
            elif kind == "task" and oid in titles:
                names.append(titles[oid])
            at, seen = owner.get(oid), seen + 1
        return " / ".join(reversed(names))

    from . import task_origin

    made_by = store.task_origins()
    made_for = {k: v for k, v in made_by.items() if task_origin.others(v)}
    tasks.sort(key=lambda t: (t.number, t.id))
    live = [t for t in tasks if not t.archived_at and t.id not in made_for]
    theirs = [t for t in tasks if not t.archived_at and t.id in made_for]
    kept = [t for t in tasks if t.archived_at]
    parts = [HEAD]
    for task in live:
        parts.append(entry(task, where(task.id), made_for=made_by.get(task.id)))
    if theirs:
        parts.append("## Made for other people\n\nTasks made on somebody else's behalf, from their email, "
                     "Telegram message or case: kept out of ‹owner›'s own lists until ‹he› shows others' "
                     "tasks. Each says who it was for.\n")
        for task in theirs:
            parts.append(entry(task, where(task.id), made_for=made_for[task.id]))
    if kept:
        parts.append("## Archived\n\nTasks archived in the task browser, kept whole and searchable there.\n")
        for task in kept:
            parts.append(entry(task, where(task.id), archived=True, made_for=made_by.get(task.id)))
    # A file in the workspace, past the places Rouh fills in the owner's marks (`rouh/owner.py`):
    # filled in here, for the installation's owner.
    from . import owner

    return owner.say("\n".join(parts))


def entry(task, project: str, *, archived: bool = False, made_for=None) -> str:
    """One task: a line saying which it is, then its summary."""
    from . import task_origin

    state = STATES.get(task.status, task.status)
    if archived:
        state += ", archived"
    # Who made it, when it was not the owner: somebody else's, or one of Rouh's processes'.
    said = task_origin.words(made_for)
    if said:
        state += ", " + said[0].lower() + said[1:]
    folder = f"`{task.folder}/`" if task.folder else "no folder"
    head = f"**{task.number}. {_one_line(task.title)}** - {folder}"
    if project:
        head += f" - {project}"
    head += f" - {state}"
    summary = (task.summary or "").strip() or NO_SUMMARY
    return f"{head}\n{summary}\n"


def _one_line(text: str) -> str:
    return " ".join(str(text or "").split()) or "Untitled"


def refresh(root: str | Path | None = None, store=None) -> bool:
    """Write the file again out of the rows if it would say something new. True when it did.

    Never raises: a task list that could not be made this time is made the next time,
    and nothing that called this is ever stopped by it.
    """
    try:
        root = str(root or _root())
        if not root or not os.path.isdir(root):
            return False
        root = Path(root)
        if store is None:
            from . import objects

            store = objects.shared_store(even_when_off=True)
        if store is None:
            return False
        text = render(store)
        path = root / NAME
        try:
            if path.read_text(encoding="utf-8") == text:
                return False
        except OSError:
            pass
        fileutil.write_atomic(path, text, spare=path.with_name(NAME + ".new"), tidy=False)
        log.info("wrote %s again out of the database", path)
        return True
    except Exception:
        log.exception("the task list could not be written out of the database")
        return False


def changed() -> None:
    """Something a task's line says may have changed: write the file now, and have it saved.

    `objecttree.WRITTEN` calls this, and so does a reconcile that changed a row.
    """
    if refresh():
        from . import saving

        saving.poke()


def _root() -> str:
    from .config import config

    return config.assistant_repo or ""


