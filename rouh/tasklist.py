# Checking it
# ---------------------------------------------------------------------------


def check(root: str | Path, store, text: str | None = None) -> list[str]:
    """What is wrong with the file, as sentences; empty when nothing is.

    Every numbered task in the database is in it exactly once, and every task folder
    on disk is named by exactly one of them.
    """
    from . import steps

    root = Path(root).resolve()
    if text is None:
        text = (root / NAME).read_text(encoding="utf-8")
    wrong = []
    tasks = [t for t in store.list_tasks(limit=1_000_000) if t.number is not None]
    for task in tasks:
        said = text.count(f"\n**{task.number}. ")
        if said != 1:
            wrong.append(f"task {task.number} is in the file {said} times")
    named = {t.folder for t in tasks if t.folder}
    for folder in steps.task_folders(root):
        rel = str(folder.relative_to(root)).replace(os.sep, "/")
        if rel not in named:
            wrong.append(f"the task folder {rel} is no task in the database")
        elif text.count(f"`{rel}/`") != 1:
            wrong.append(f"the task folder {rel} is in the file {text.count(f'`{rel}/`')} times")
    return wrong


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m rouh.tasklist",
        description="Write or check workspace/_tasks.md, which is generated from Rouh's database.")
    parser.add_argument("what", choices=("print", "write", "check"), nargs="?", default="check")
    parser.add_argument("--root", default="", help="the workspace (default: Rouh's own)")
    args = parser.parse_args(argv)
    from .project import setup

    setup()
    from . import objects

    store = objects.shared_store(even_when_off=True)
    if store is None:
        print("no database to read the tasks from", file=sys.stderr)
        return 2
    root = Path(args.root or _root())
    if args.what == "print":
        sys.stdout.write(render(store))
        return 0
    if args.what == "write":
        print("written" if refresh(root, store) else "already up to date")
    wrong = check(root, store)
    for sentence in wrong:
        print(sentence)
    print(f"{len(wrong)} problems" if wrong else "every task is in it once, and every task folder")
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
